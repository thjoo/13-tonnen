import asyncio,sys,json,os,tempfile
from playwright.async_api import async_playwright
W=int(sys.argv[1]);P=os.path.join(tempfile.gettempdir(),"gruppe_%d_"%W)
async def until(pg,js,t=60000):
    await pg.wait_for_function(js,timeout=t,polling=300)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--no-sandbox"])
        ctx=await b.new_context(viewport={"width":W,"height":860},reduced_motion="reduce");pg=await ctx.new_page()
        log=[];pg.on("pageerror",lambda e:log.append("PAGEERROR "+str(e)[:300]))
        pg.on("console",lambda m:log.append("CONSOLE "+m.text[:200]) if m.type=="error" else None)
        await pg.add_init_script("localStorage.setItem('13t_intro','1');localStorage.setItem('13t_tut','1');")
        await pg.goto("http://localhost:8765/index.html");await pg.wait_for_timeout(800)
        await pg.evaluate("()=>{S.screen='start';render();const k=document.querySelector('#klasse');if(k)k.value='TEST';Group.create()}")
        await until(pg,"()=>typeof G!=='undefined'&&G&&typeof ROOM!=='undefined'&&ROOM&&ROOM.players",45000)
        code=await pg.evaluate("()=>G.code");print("Raum",code)
        await pg.evaluate("()=>Bots.add(3)");await pg.wait_for_timeout(2500)
        await pg.evaluate("()=>Group.pickFig('Ruth')")
        await until(pg,"()=>G.players().length>=4&&G.players().every(p=>p.fig)")
        await pg.screenshot(path=P+"lobby.png",full_page=True)
        print("test-Flag",await pg.evaluate("()=>ROOM.test"))
        await pg.evaluate("()=>Group.start()")
        for r in range(4):
            await until(pg,f"()=>S.screen==='round'&&S.r==={r}",60000);await pg.wait_for_timeout(800)
            await pg.evaluate("()=>{S.crisisSeen=S.r;for(const id of S.hand){if(!blocked(id)){choose(id);break;}}for(const k of S.ballot)if(freeH()>0)alloc(k,1);render();vote(true)}")
            await until(pg,"()=>!!document.querySelector('.vov')",90000)
            await pg.wait_for_timeout(400)
            behind=await pg.evaluate("()=>{const a=document.getElementById('app').innerText;return /Angenommen|Abgelehnt/.test(a)}")
            await pg.screenshot(path=P+f"sendung_r{r}.png")
            await until(pg,"()=>!!document.querySelector('#vgo')",30000)
            txt=await pg.evaluate("()=>document.querySelector('.vcols').innerText.replace(/\\n+/g,' | ').slice(0,300)")
            await pg.evaluate("()=>document.querySelector('#vgo').click()");await pg.wait_for_timeout(500)
            print("Runde",r,"Ergebnis im App-Text waehrend Sendung:",behind,"|",txt)
            await pg.evaluate("()=>toEvent()");await pg.wait_for_timeout(1500)
            await pg.evaluate("()=>{if(S.screen==='dorf')toSummary()}");await pg.wait_for_timeout(4000)
            ov=await pg.evaluate("()=>!!document.querySelector('.vov')")
            gp=await pg.evaluate("()=>{const g=document.querySelector('.groupbox,.gpanel');return (document.body.innerText.match(/Budget[^\\n]*/)||[''])[0]}")
            hd=await pg.evaluate("()=>document.querySelector('.top')?document.querySelector('.top').innerText.replace(/\\n+/g,' '):''")
            await pg.screenshot(path=P+f"bilanz_r{r}.png",full_page=True)
            print("  Sendung ueber Bilanz:",ov,"|",gp,"|",hd[:120])
            if r<3: await pg.evaluate("()=>nextRound()")
        await pg.evaluate("()=>nextRound()");await pg.wait_for_timeout(1500)
        await pg.evaluate("()=>{if(S.screen==='dorf')toEnd()}");await pg.wait_for_timeout(1500);print('Outro offen:',await pg.evaluate("()=>!!document.querySelector('.ovl.outro')"));await pg.evaluate("()=>outroEnd()");await pg.wait_for_timeout(3000)
        print("Ende Screen",await pg.evaluate("()=>S.screen"),"Sendung:",await pg.evaluate("()=>!!document.querySelector('.vov')"))
        await pg.screenshot(path=P+"ende.png",full_page=True)
        print("Punkte:",await pg.evaluate("()=>{const h=[...document.querySelectorAll('.sec h2')].find(x=>x.innerText.toLowerCase().includes('punkte'));return h?h.parentElement.nextElementSibling.innerText.replace(/\\n+/g,' | ').slice(0,200):'-'}"));print("Bestenliste-Eintrag?",await pg.evaluate("()=>JSON.stringify({test:ROOM.test,board:S.boardSent||null})"))
        print("\n".join(log[:15]))
        await pg.evaluate("()=>{try{G.leave()}catch(e){}}");await pg.wait_for_timeout(1000)
        await b.close()
asyncio.run(main())
